// Builds src/app/data/screenshots.generated.js from the folders in src/app/img/projects/.
//
// Add screenshots by dropping image files into src/app/img/projects/<project-slug>/ (the slug is the
// project's URL name, e.g. pythonapi-fastapi-exercise), then run `npm run shots`. `npm run dev` and
// `npm run build` run it automatically. Files are shown in filename order, so prefix them with
// numbers: 01-home.webp, 02-search.webp.
//
// Portrait images (taller than wide, like phone screenshots) are left out of the 4:3 slideshows. They are
// still imported and available by name, e.g. files['poll-the-vote/calendar.webp'], for pages that place them
// next to text (the Poll The Vote walkthroughs).
//
// Optional: a captions.json in the folder sets the caption and alt text per file:
//   { "01-home.webp": "Home page" }                                     (one string = caption and alt)
//   { "01-home.webp": { "caption": "Home", "alt": "Long description" } }
// Without it, the caption comes from the filename ("02-search-results.webp" -> "Search results").
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const projectsDir = join(root, 'src/app/img/projects');
const outFile = join(root, 'src/app/data/screenshots.generated.js');

const IMAGE_EXT = new Set(['.webp', '.png', '.jpg', '.jpeg', '.avif']);
const collator = new Intl.Collator('en', { numeric: true, sensitivity: 'base' });

function captionFromName(file) {
  const base = file.slice(0, file.length - extname(file).length);
  const words = base.replace(/^[\d\s._-]+/, '').replace(/[-_]+/g, ' ').trim();
  if (!words || /^(screenshot|screen shot|image|img|capture|untitled)\b/i.test(words)) return '';
  return words.charAt(0).toUpperCase() + words.slice(1);
}

function readOverrides(dir) {
  const file = join(dir, 'captions.json');
  if (!existsSync(file)) return {};
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    console.warn(`screenshots: could not read ${file}: ${error.message}`);
    return {};
  }
}

const slugs = existsSync(projectsDir)
  ? readdirSync(projectsDir)
      .filter((name) => statSync(join(projectsDir, name)).isDirectory())
      .sort(collator.compare)
  : [];

// sharp ships with Next.js. If it is missing, every image is treated as landscape.
let sharp = null;
try {
  sharp = (await import('sharp')).default;
} catch {
  console.warn('screenshots: sharp not found, cannot tell portrait images apart');
}

async function isPortrait(file) {
  if (!sharp) return false;
  const { width, height } = await sharp(file).metadata();
  return height > width;
}

const imports = [];
const entries = [];
const byName = [];
const portraitSkipped = [];
let counter = 0;

for (const slug of slugs) {
  const dir = join(projectsDir, slug);
  const files = readdirSync(dir)
    .filter((file) => IMAGE_EXT.has(extname(file).toLowerCase()))
    .sort(collator.compare);
  if (files.length === 0) continue;

  const overrides = readOverrides(dir);
  const shots = [];
  for (const file of files) {
    const name = `shot${counter++}`;
    imports.push(`import ${name} from ${JSON.stringify(`../img/projects/${slug}/${file}`)};`);
    byName.push(`  ${JSON.stringify(`${slug}/${file}`)}: ${name},`);

    if (await isPortrait(join(dir, file))) {
      portraitSkipped.push(`${slug}/${file}`);
      continue;
    }
    const override = overrides[file];
    const caption = typeof override === 'string' ? override : (override?.caption ?? captionFromName(file));
    const alt = typeof override === 'string' ? override : (override?.alt ?? '');
    shots.push(`    { src: ${name}, caption: ${JSON.stringify(caption)}, alt: ${JSON.stringify(alt)} },`);
  }
  if (shots.length > 0) entries.push(`  ${JSON.stringify(slug)}: [\n${shots.join('\n')}\n  ],`);
}

const output = `// AUTO-GENERATED by scripts/generate-screenshots.mjs. Do not edit by hand.
// Add screenshots to src/app/img/projects/<project-slug>/ and run \`npm run shots\`.
${imports.join('\n')}

// Landscape images per project, for the slideshows.
const screenshots = {
${entries.join('\n')}
};

// Every image by "<slug>/<filename>", portrait ones included.
export const files = {
${byName.join('\n')}
};

export default screenshots;
`;

if (portraitSkipped.length > 0) {
  console.log(`screenshots: portrait, not in slideshows: ${portraitSkipped.join(', ')}`);
}

const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (current !== output) {
  writeFileSync(outFile, output);
  console.log(`screenshots: wrote ${counter} screenshot(s) for ${entries.length} project(s)`);
} else {
  console.log(`screenshots: up to date (${counter} screenshot(s), ${entries.length} project(s))`);
}
